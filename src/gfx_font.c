/**
 * Returns the 8×8 bitmap rows for ch (space for non-printable).
 */
const uint8_t *haeun_gfx_font8_rows(char ch) {
    unsigned u = (unsigned char)ch;
    if (u >= 32u && u <= 126u) return FONT8[u - 32u];
    return FONT8[0];
}

static const uint8_t *glyph_rows(char ch) { return haeun_gfx_font8_rows(ch); }

/**
 * Draws one 8×8 glyph; non-printable characters become a solid block.
 */
haeun_gfx_result haeun_gfx_draw_char(haeun_gfx *gfx, uint32_t x, uint32_t y,
                                     char ch, uint32_t fg, uint32_t bg) {
    const uint8_t *rows;
    unsigned u;
    uint32_t row, col;
    if (gfx == NULL || !haeun_gfx_fb_ready(gfx)) return HAEUN_GFX_NOT_READY;
    u = (unsigned char)ch;
    if (u < 32u || u > 126u) {
        return haeun_gfx_fill_rect(gfx, x, y, 8u, 8u, fg);
    }
    rows = glyph_rows(ch);
    for (row = 0u; row < 8u; ++row) {
        uint8_t bits = rows[row];
        for (col = 0u; col < 8u; ++col) {
            uint32_t px = (bits & (uint8_t)(1u << col)) != 0u ? fg : bg;
            haeun_gfx_result r = haeun_gfx_put_pixel(gfx, x + col, y + row, px);
            if (r == HAEUN_GFX_OOB) continue;
            if (r != HAEUN_GFX_OK) return r;
        }
    }
    return HAEUN_GFX_OK;
}

/**
 * Draws text with 8-pixel advance; '\\n' moves to the next line.
 */
haeun_gfx_result haeun_gfx_draw_string(haeun_gfx *gfx, uint32_t x, uint32_t y,
                                       const char *text, uint32_t fg,
                                       uint32_t bg) {
    uint32_t cx;
    uint32_t cy;
    uint32_t origin;
    if (gfx == NULL || text == NULL || !haeun_gfx_fb_ready(gfx))
        return HAEUN_GFX_NOT_READY;
    cx = x;
    cy = y;
    origin = x;
    while (*text != '\0') {
        char ch = *text++;
        haeun_gfx_result r;
        if (ch == '\r')
            continue;
        if (ch == '\n') {
            cx = origin;
            cy += 8u;
            continue;
        }
        r = haeun_gfx_draw_char(gfx, cx, cy, ch, fg, bg);
        if (r != HAEUN_GFX_OK && r != HAEUN_GFX_OOB)
            return r;
        cx += 8u;
    }
    return HAEUN_GFX_OK;
}
