/**
 * M20.8 integration harness helpers.
 */
#include "m20_integration_harness.h"

#include <string.h>

void m20i_wr32(uint8_t *p, uint32_t v) {
    p[0] = (uint8_t)v;
    p[1] = (uint8_t)(v >> 8);
    p[2] = (uint8_t)(v >> 16);
    p[3] = (uint8_t)(v >> 24);
}

void m20i_prep_pcb(uint8_t *ram, size_t n) {
    int i;
    memset(ram, 0, n);
    for (i = 0; i < 4; ++i)
        m20i_wr32(ram + M20I_PCB_BASE + (uint32_t)i * M20I_PCB_STRIDE, 0u);
    m20i_wr32(ram + M20I_PCB_NEXT, 2u);
    m20i_wr32(ram + 0xA400u, 0u);
    m20i_wr32(ram + M20I_PCB_BASE + 4u, 1u);
    m20i_wr32(ram + M20I_PCB_BASE + 0u, 2u);
}

/** Minimal HXF with one short code block for app spawn tests. */
void m20i_make_tiny_hxf(uint8_t *out, size_t *out_len) {
    uint8_t code[8] = {0, 0, 0, 0, 0x00, 0x00, 0x00, 0x04};
    size_t total = 96u + sizeof(code);
    memset(out, 0, total);
    out[0] = 'H';
    out[1] = 'X';
    out[2] = 'F';
    out[3] = '1';
    out[4] = 64;
    out[6] = 1;
    out[8] = 4;
    out[16] = 0x00;
    out[17] = 0x80;
    out[18] = 0x10;
    out[19] = 0x00;
    out[20] = 64;
    out[24] = 1;
    out[26] = 32;
    out[28] = (uint8_t)total;
    out[64] = 1;
    out[68] = 7;
    out[72] = 96;
    out[76] = 0x00;
    out[77] = 0x80;
    out[78] = 0x10;
    out[79] = 0x00;
    out[80] = (uint8_t)sizeof(code);
    out[84] = (uint8_t)sizeof(code);
    out[88] = 4;
    memcpy(out + 96, code, sizeof(code));
    *out_len = total;
}
